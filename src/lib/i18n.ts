let currentLocale: Locale = (localStorage.getItem("mvo-locale") as Locale) || "en";
if (!translations[currentLocale]) currentLocale = "en";

type LocaleListener = () => void;
const localeListeners = new Set<LocaleListener>();

export function setLocale(locale: Locale) {
  if (!translations[locale]) locale = "en";
  currentLocale = locale;
  localStorage.setItem("mvo-locale", locale);
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = locale;
  localeListeners.forEach(fn => fn());
}

export function subscribeLocale(fn: LocaleListener): () => void {
  localeListeners.add(fn);
  return () => { localeListeners.delete(fn); };
}

export function initLocale() {
  const saved = (localStorage.getItem("mvo-locale") as Locale) || "en";
  setLocale(saved);
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(key: string): string {
  return translations[currentLocale]?.[key] || translations.en[key] || key;
}

